// eslint-disable-next-line @typescript-eslint/no-unused-expressions -- playwright-cli evaluates this function expression.
async page => {
  const origin = "http://127.0.0.1:5173";
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(origin);
  if (await page.locator('meta[name="zenshin-ui-preview"]').getAttribute("content") !== "fixtures-only") throw new Error("Run only against the isolated fixture preview.");
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const filters = page.getByRole("button", { name: /^Filters/ }).first();
  await filters.focus();
  await filters.press("Enter");
  const filterDialog = page.getByRole("dialog", { name: "Filter tasks" });
  await filterDialog.waitFor();
  assert(await filterDialog.evaluate(el => el.contains(document.activeElement)), "Filters did not receive focus.");
  await page.keyboard.press("Escape");
  await filterDialog.waitFor({ state: "hidden" });
  assert(await filters.evaluate(el => document.activeElement === el), "Filters did not restore focus.");
  checks.push("Filter keyboard focus and Escape restoration");
  const task = page.locator("[data-task-link]").first();
  await task.waitFor();
  const href = await task.getAttribute("href");
  await task.focus();
  await task.press("Enter");
  const title = page.getByRole("button", { name: /^Edit title:/ });
  await title.waitFor();
  assert(await page.getByRole("heading", { level: 1 }).filter({ has: title }).count() === 1, "Task title must remain a heading.");
  await title.focus();
  await title.press("Space");
  const editor = page.getByRole("textbox", { name: "Task title", exact: true });
  await editor.waitFor();
  await editor.press("Control+k");
  assert(await page.getByRole("dialog", { name: "Search", exact: true }).count() === 0, "Search shortcut intercepted editing.");
  await editor.press("Escape");
  await title.waitFor();
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label")?.startsWith("Edit title:"));
  await page.getByRole("button", { name: "Close task", exact: true }).click();
  await page.waitForFunction(() => !new URLSearchParams(location.search).has("task"));
  await page.waitForFunction(() => document.activeElement?.matches("[data-task-link]"));
  assert(await page.locator(`[data-task-link][href='${href}']`).first().evaluate(el => document.activeElement === el), "Closing task did not restore focus.");
  checks.push("Heading, Space edit, editor shortcut isolation, Escape and close focus");

  await page.keyboard.press("Control+k");
  await page.getByRole("combobox", { name: "Search projects, sections and tasks" }).waitFor();
  await page.getByRole("button", { name: "Close search", exact: true }).click();
  await page.goto(`${origin}/search?q=panel`);
  const search = page.getByRole("textbox", { name: "Search projects, sections and tasks" });
  await search.waitFor();
  await page.getByRole("button", { name: /^Filters/ }).click();
  await page.getByRole("dialog", { name: "Filter tasks" }).waitFor();
  assert(await page.locator("form form").count() === 0, "Search contains nested forms.");
  await page.keyboard.press("Escape");
  await page.evaluate(() => { history.pushState(null, "", "/search?q=drafts"); window.dispatchEvent(new PopStateEvent("popstate")); });
  await page.waitForFunction(() => document.querySelector('input[aria-label="Search projects, sections and tasks"]')?.value === "drafts");
  await page.goBack();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Search projects, sections and tasks"]')?.value === "panel");
  checks.push("Search close and browser Back query text");

  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.goto(origin);
  await page.getByRole("button", { name: "Toggle navigation" }).click();
  const navigation = page.getByRole("dialog", { name: "Workspace navigation" });
  await navigation.waitFor();
  await navigation.getByRole("button", { name: "Search", exact: false }).click();
  const close = page.getByRole("button", { name: "Close search", exact: true });
  await close.waitFor();
  const bounds = await close.boundingBox();
  assert(bounds && bounds.height >= 44, "Mobile search close target is too short.");
  await close.click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile page overflows horizontally.");
  checks.push("Mobile navigation/search, dark/reduced-motion rendering, no page overflow");
  await page.emulateMedia({ colorScheme: "light", reducedMotion: "reduce" });
  await page.goto(`${origin}/?settings=preferences`);
  const preferences = page.getByRole("dialog", { name: "Preferences", exact: true });
  await preferences.waitFor();
  for (const width of [639, 640, 700, 767, 768]) {
    await page.setViewportSize({ width, height: 900 });
    const field = await preferences.getByRole("textbox", { name: "Timezone", exact: true }).boundingBox();
    assert(field && field.width > 200 && field.x >= 0 && field.x + field.width <= width, `Settings content is clipped at ${width}px.`);
  }
  const timezone = preferences.getByRole("textbox", { name: "Timezone", exact: true });
  await timezone.fill("America/New_York");
  await page.getByRole("button", { name: "Agent credentials", exact: true }).click();
  await page.getByRole("dialog", { name: "Agent credentials", exact: true }).waitFor();
  await page.goBack();
  await preferences.waitFor();
  assert(await timezone.inputValue() === "America/New_York", "Settings navigation lost the preference draft.");
  await preferences.getByRole("button", { name: "Discard draft and reload preferences" }).click();
  checks.push("Settings breakpoint boundaries, URL Back, and draft recovery");

  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole("button", { name: "Agent credentials", exact: true }).click();
  await page.getByRole("button", { name: "Create key", exact: true }).click();
  const credential = page.getByRole("dialog", { name: "Create agent key", exact: true });
  await credential.getByRole("textbox", { name: "Name", exact: true }).fill("UI audit fixture");
  await credential.getByRole("checkbox", { name: "Zenshin", exact: true }).check();
  await credential.getByRole("button", { name: "Create key", exact: true }).click();
  const secret = page.getByRole("textbox", { name: "New agent secret", exact: true });
  await secret.waitFor();
  assert(await secret.inputValue() === "preview-only-not-a-real-credential", "Fixture key reveal is missing.");
  await page.getByRole("dialog", { name: "Agent credentials", exact: true }).getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Agent credentials", exact: true }).click();
  await secret.waitFor();
  assert(await secret.inputValue() === "preview-only-not-a-real-credential", "Closing settings lost the unacknowledged reveal.");
  await page.getByRole("button", { name: "I’ve stored it", exact: true }).click();
  checks.push("One-time fixture reveal survives settings dismissal until acknowledged");

  await page.goto(origin);
  await page.keyboard.press("c");
  assert(await page.getByRole("dialog", { name: "New task", exact: true }).count() === 0, "Single-character shortcut still opens creation.");
  await page.keyboard.press("Alt+Shift+N");
  const create = page.getByRole("dialog", { name: "New task", exact: true });
  await create.getByRole("textbox", { name: "Title", exact: true }).fill("Retained UI draft");
  await create.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "New task", exact: true }).click();
  assert(await create.getByRole("textbox", { name: "Title", exact: true }).inputValue() === "Retained UI draft", "Creation draft was lost.");
  await create.getByRole("button", { name: "Discard draft", exact: true }).click();
  checks.push("Modified create shortcut and dismissal draft retention");

  await page.locator("[data-task-link]").first().click();
  await page.getByRole("button", { name: /^Labels:/ }).click();
  await page.evaluate(() => {
    const fetch = window.fetch;
    window.fetch = async (input, init) => {
      if (String(input).includes("/labels") && init?.method === "POST") await new Promise(resolve => setTimeout(resolve, 500));
      return fetch(input, init);
    };
  });
  const option = page.getByRole("option", { name: "Frontend", exact: true });
  await option.click();
  assert(await option.isDisabled(), "A second property change is accepted while saving.");
  await page.waitForFunction(() => document.querySelector('[aria-label="Task properties"]')?.getAttribute("aria-busy") === "false");
  assert(!await option.isDisabled(), "Property choices stay disabled after saving.");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Close task", exact: true }).click();
  checks.push("Slow property save locks choices and restores editing");

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${origin}/search?q=panel`);
  await page.getByRole("button", { name: /^Filters/ }).click();
  const popup = page.getByRole("dialog", { name: "Filter tasks", exact: true });
  await popup.waitFor();
  const popupBounds = await popup.boundingBox();
  assert(popupBounds && popupBounds.x >= 0 && popupBounds.x + popupBounds.width <= 390, "Filter form extends outside the mobile viewport.");
  await popup.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.goto(`${origin}/projects/00000000-0000-4000-8000-000000000001?view=calendar`);
  const today = page.locator('.calendar-day-select[aria-current="date"]');
  await today.click();
  assert(await page.locator(".calendar-agenda").isVisible(), "Mobile calendar does not show a readable agenda.");
  const dayBounds = await today.boundingBox();
  assert(dayBounds && dayBounds.height >= 44, "Calendar day target is too short.");
  checks.push("Mobile filter collision handling and calendar agenda");
  return { checks, limitations: "Fixture interactions only. Real Next navigation scroll, contrast/screen-reader/zoom audit, uploads, providers and signed-in staging acceptance remain separate." };
}
