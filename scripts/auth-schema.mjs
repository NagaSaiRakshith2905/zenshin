import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const output = "src/server/db/schema/auth.generated.ts";
execFileSync("pnpm", ["exec", "auth", "generate", "--config", "scripts/auth-schema.config.ts", "--adapter", "drizzle", "--dialect", "postgresql", "--output", output, "--yes"], { stdio: "inherit" });
const generated = readFileSync(output, "utf8");
if (!generated.includes('export const apikey = pgTable(') || !generated.includes('referenceId: text("reference_id")')) {
  throw new Error("Auth generator output changed; review identifiers and adapter mappings before regenerating migrations.");
}
// The generated Date fields remain Date fields; PostgreSQL stores their instants explicitly.
writeFileSync(output, "// Generated by pnpm db:auth:generate; timestamp types normalized to UTC timestamptz.\n" + generated.replace(/timestamp\("([^"\n]+)"\)/g, 'timestamp("$1", { withTimezone: true })'));
